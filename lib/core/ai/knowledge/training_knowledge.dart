/// Компактное ядро универсальных принципов тренировочного процесса.
///
/// Подключается во все AI-промпты (генерация плана, коррекция, чат), чтобы
/// решения AI были согласованы и обоснованы физиологией/биомеханикой, а не
/// произвольными шаблонами. Основано на консенсусе ACSM/NSCA и общих
/// принципах спортивной науки, а не на одной конкретной авторской школе.
const String trainingPrinciplesCore = '''
═══ ПРИНЦИПЫ ТРЕНИРОВОЧНОГО ПРОЦЕССА ═══
Ты принимаешь решения на основе физиологии и биомеханики, а не единственной "методики". Следуй этим принципам (консенсус ACSM/NSCA):
1. Прогрессивная перегрузка — прогрессируй по ЛЮБОЙ из осей, не только весом: вес, повторения, объём (подходы), плотность (меньше отдых), время под нагрузкой, амплитуда (ROM), скорость, сложность вариации упражнения.
2. Специфичность — тренировка должна соответствовать цели пользователя (похудение ≠ набор массы ≠ спортивный результат ≠ здоровье); не копируй упражнения из чужой цели "для разнообразия".
3. Индивидуальность — возраст, пол, стаж тренировок, восстановление и ограничения важнее общих шаблонов.
4. Обратимость — после перерыва >10-14 дней снижай стартовый объём/интенсивность на 20-30% и наращивай заново, а не продолжай с прежней точки.
5. Вариативность — не повторяй одну и ту же комбинацию упражнений дольше 4-6 недель подряд без изменения угла, инвентаря или схемы подходов/повторений.
6. Восстановление первично — результат даёт сон+питание+отдых не меньше, чем сама тренировка; при признаках недовосстановления снижай нагрузку раньше, чем сорвётся прогресс.
7. RPE/RIR — используй шкалу RPE 1-10 (RIR = 10-RPE = повторений "в запасе") для дозирования интенсивности вместо только процентов от 1ПМ, особенно когда точный 1ПМ неизвестен.
''';

/// Выбирает 2-4 релевантные для ЭТОГО пользователя директивы (аналог дерева
/// решений тренера), вместо того чтобы каждый раз описывать все возможные
/// методологии — так модель не теряет релевантный сигнал в шуме.
String methodologyEmphasisBlock(
  UserProfile profile, {
  RecoveryScore? recovery,
  int? recentAvgRpe,
  int? domsLevel,
}) {
  final directives = <String>[];

  if (recovery != null && recovery.shouldReduceIntensity) {
    directives.add(
      '— Восстановление снижено (сон/HRV/пульс покоя вне нормы) → снизь плановый объём и интенсивность этой недели на 15-20%, замени 1-2 тяжёлых базовых упражнения на лёгкие/восстановительные, не допускай подходов до отказа.',
    );
  }

  if (recentAvgRpe != null && recentAvgRpe >= 8) {
    directives.add(
      '— Пользователь стабильно оценивает свои последние тренировки как тяжёлые (средний RPE $recentAvgRpe/10) → это признак накопленной усталости: спланируй разгрузочную неделю (объём -30-40%) или снизь интенсивность, не жди явных признаков перетренированности.',
    );
  }

  if (domsLevel != null && domsLevel >= 2) {
    directives.add(
      '— Пользователь сегодня отмечает заметную/сильную мышечную боль (DOMS уровень $domsLevel/3) → дай болящим мышечным группам дополнительный день отдыха или замени их на лёгкую активность/мобильность, не нагружай их повторно, пока боль не спадёт.',
    );
  }

  final isNoviceContext =
      profile.trainingExperience == TrainingExperience.novice ||
      profile.intensity == IntensityLevel.relaxed ||
      profile.goal == FitnessGoal.maintain;
  if (isNoviceContext) {
    directives.add(
      '— Профиль начинающего/оздоровительный: приоритет — общая физическая подготовка (база: приседания, отжимания, тяга, ходьба/лёгкое кардио), техника важнее веса, RPE не выше 7-8, НЕ доводи подходы до мышечного отказа.',
    );
  }

  final isAdvancedPerformance =
      profile.goal == FitnessGoal.sportPerformance &&
      (profile.trainingExperience == TrainingExperience.experienced ||
          profile.intensity == IntensityLevel.intensive ||
          profile.intensity == IntensityLevel.hardcore);
  if (isAdvancedPerformance) {
    directives.add(
      '— Цель — спортивный результат, стаж/интенсивность продвинутые: добавь взрывные/плиометрические элементы (прыжки, броски, ускорения) для развития мощности; при выборе упражнений отдавай приоритет тем, что имеют наибольший перенос на целевой навык/дистанцию, а не просто нагружают ту же мышцу.',
    );
  } else if (profile.goal == FitnessGoal.gainWeight &&
      profile.intensity != IntensityLevel.relaxed &&
      profile.intensity != IntensityLevel.gradual) {
    directives.add(
      '— Цель — набор массы, средняя/высокая интенсивность: держи больший еженедельный объём при умеренной интенсивности (не всегда близко к отказу), с обязательной отработкой техники базовых движений перед ростом весов.',
    );
  }

  if (directives.isEmpty) return '';
  return '═══ АКЦЕНТЫ ДЛЯ ЭТОГО ПОЛЬЗОВАТЕЛЯ ═══\n${directives.join('\n')}\n';
}
